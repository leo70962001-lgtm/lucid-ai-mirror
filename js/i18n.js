const IDX = { zh: 0, en: 1, ja: 2 };
let lang = 'zh';

export function getLang() { return lang; }

export function setLang(l) {
  if (!(l in IDX)) return;
  lang = l;
  try { localStorage.setItem('lucid-lang', l); } catch { /* 無痕模式沒有 localStorage，不影響功能 */ }
  document.documentElement.lang = l === 'zh' ? 'zh-Hant' : l;
}

export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem('lucid-lang'); } catch { /* 同上 */ }
  const nav = (globalThis.navigator?.language || '').toLowerCase();
  setLang(saved || (nav.startsWith('ja') ? 'ja' : nav.startsWith('zh') ? 'zh' : nav ? 'en' : 'zh'));
}

/** t('key', { n: 3 })。找不到 key 就原樣回傳 key —— 缺翻譯時畫面不會變成空白 */
export function t(key, vars) {
  const row = DICT[key];
  let s = row ? (row[IDX[lang]] ?? row[0]) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
  return s;
}

/** 商品／妝容這種「資料本身」的翻譯：物件上帶 name_en / name_ja */
export const tf = (obj, field) => (lang === 'zh' ? obj[field] : obj[field + '_' + lang] || obj[field]);

/** 套用 index.html 裡的 data-i18n / data-i18n-title */
export function applyStatic(root = document) {
  for (const e of root.querySelectorAll('[data-i18n]')) e.textContent = t(e.dataset.i18n);
  for (const e of root.querySelectorAll('[data-i18n-title]')) e.title = t(e.dataset.i18nTitle);
}
